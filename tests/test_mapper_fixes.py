class TestSmartMappingGeneration:
    """Smart Mapping debe generar json.dumps/json.loads en el mapper."""

    def test_mapper_has_json_imports(self, generated_project):
        content = _read(generated_project, "infrastructure", "mappers", "pet", "pet_mapper.py")
        assert "import json" in content, "Mapper con Smart Mapping debe importar json"

    def test_mapper_has_json_loads_for_read(self, generated_project):
        content = _read(generated_project, "infrastructure", "mappers", "pet", "pet_mapper.py")
        assert "json.loads" in content or "_safe_json_loads" in content, \
            "Mapper debe usar json.loads o _safe_json_loads para leer photoUrls"

    def test_mapper_has_json_dumps_for_write(self, generated_project):
        content = _read(generated_project, "infrastructure", "mappers", "pet", "pet_mapper.py")
        assert "json.dumps" in content, \
            "Mapper debe usar json.dumps para escribir photoUrls"

    def test_photo_urls_uses_persistence_column(self, generated_project):
        """Smart Mapping accede directo a entity.photo_urls (columna snake_case)."""
        content = _read(generated_project, "infrastructure", "mappers", "pet", "pet_mapper.py")
        # Smart Mapping usa acceso directo con entity.photo_urls (no el patrón unloaded)
        assert "entity.photo_urls" in content, \
            "photoUrls debe leer entity.photo_urls (columna snake_case)"
        assert "entity.photoUrls" not in content, \
            "No debe acceder entity.photoUrls (camelCase)"
